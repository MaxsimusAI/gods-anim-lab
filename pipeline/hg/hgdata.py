    nu = {}
    for slot, (mf, key) in G['sheets'].items():
        m = json.load(open(mf))[key]
        srcf = G['files'].get(slot, m['file'])
        dst = f'assets/hg/new/{G["id"]}-bt-{slot}.webp'; shutil.copy(srcf, f'{REPO}/{dst}')
        nu[slot] = {'src': f'{dst}?v={V["v"]}', 'cols': 5, 'rows': 5, 'n': 25, 'fw': m['fw'], 'fh': m['fh'], 'dur': 3.0, 'fig': m['fig'], 'kb': round(os.path.getsize(srcf) / 1024)}
