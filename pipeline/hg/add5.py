# add5.py: put the five goddesses drawn 27.11 (task 238: Time, Pogibel, Fear, Umbra, Ocean) on the review page.
# hgdata.py cannot be re-run here (it needs the whole cutting workspace of 26-27.11), so this script appends the five entries
# to assets/hg/hg-data.js (replacing them if present) and bumps the version stamp of every sheet, the data and the stand.
# Sheets: /home/claude/hgk/sheets3/<god>.json + <god>-bt-<slot>.webp (hgcut3.py, matte v3); release points: rel.json; notes and game-effect lines: notes5.json.
import json, os, re, shutil
REPO = '/home/claude/gods-anim-lab'; HG = os.path.dirname(os.path.abspath(__file__)); WS = '/home/claude/hgk'
REL = json.load(open(f'{HG}/rel.json')); NOTES = json.load(open(f'{HG}/notes5.json')); V = json.load(open(f'{HG}/ver.json'))
V['v'] += 1; v = V['v']
FIVE = [   # skill names and texts from idolrpg src/sim/modes/convergence.js
 ('time', 'Время', 'Поворот времён', 'Атакует каждого врага. Союзники сразу готовы атаковать. Союзники 6 сек атакуют на 15% быстрее.'),
 ('pogibel', 'Погибель', 'Багровый закат', 'Атакует каждого врага.'),
 ('fear', 'Страх', 'Оцепенение', 'Атакует каждого врага. Оглушает всех врагов на 3 сек. Все враги 6 сек наносят на 15% меньше урона.'),
 ('umbra', 'Тьма', 'Затмение', 'Атакует каждого врага. Все враги не могут применять супер-удар и ульту. Боги Тьмы наносят больше урона.'),
 ('ocean', 'Вода', 'Прилив', 'Перед ударом снимает щиты врагов. Атакует каждого врага. Лечит каждого союзника, богов Воды вдвое больше.'),
]
p = f'{REPO}/assets/hg/hg-data.js'; s = open(p).read(); i = s.index('const HG = ') + len('const HG = ')
arr, _ = json.JSONDecoder().raw_decode(s[i:])
ids = {g[0] for g in FIVE}; arr = [G for G in arr if G['id'] not in ids]
for gid, name, skill, desc in FIVE:
    m = json.load(open(f'{WS}/sheets3/{gid}.json')); nu = {}
    if not REL.get(gid, {}).get('atk', {}).get('wf'): raise SystemExit(f'no release point for {gid}')
    for slot in ('idle', 'app', 'atk'):
        dst = f'assets/hg/new/{gid}-bt-{slot}.webp'; shutil.copy(f'{WS}/sheets3/{gid}-bt-{slot}.webp', f'{REPO}/{dst}')
        nu[slot] = {'src': f'{dst}?v={v}', 'cols': 5, 'rows': 5, 'n': 25, 'fw': m[slot]['fw'], 'fh': m[slot]['fh'], 'dur': 3.0,
                    'fig': {k: float(x) for k, x in m[slot]['fig'].items()}, 'kb': m[slot]['kb']}
        nu[slot].update(REL[gid].get(slot, {}))
    N = NOTES[gid]
    arr.append({'id': gid, 'name': name, 'skill': skill, 'desc': desc, 'fx': gid, 'live': None,
                'fxNote': N['fx'], 'nu': nu, 'notes': N['notes'], 'accepted': False})
for G in arr:   # one stamp for every picture: a re-cut under the same name reaches the viewers
    for grp in ('nu', 'live'):
        for sh in (G.get(grp) or {}).values(): sh['src'] = sh['src'].split('?')[0] + f'?v={v}'
js = f'/* generated by hgdata.py: higher goddesses on the review page (the last five appended by add5.py) */\nconst HG_V = {v};\nconst HG = ' + json.dumps(arr, ensure_ascii=False, indent=1) + ';\n'
open(p, 'w').write(js)
hp = f'{REPO}/higher.html'; h = open(hp).read(); open(hp, 'w').write(re.sub(r'(assets/hg/hg-(?:data|stand)\.js)\?v=\d+', lambda mm: f'{mm.group(1)}?v={v}', h))
json.dump(V, open(f'{HG}/ver.json', 'w')); print('goddesses', len(arr), 'version', v)
